"""Render the validated schema-v3 loading results into fail-closed LaTeX macros.

Run only after ``analysis/loading_table.py --check`` succeeds. The manuscript deliberately
requires this generated file, so stale c^2/lambda values cannot silently survive a rebuild.

    python analysis/loading_table_tex.py           # validate and write macros atomically
    python analysis/loading_table_tex.py --check   # validate and require an exact existing file
"""
from pathlib import Path
import json
import math
import sys

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "calibration_figures" / "loading_table.json"
OUT = ROOT / "submissions" / "jmlr_ceiling" / "generated" / "loading_table_values.tex"
SCHEMA = "loading_perpoint/3"
CANON = [
    ("Burgers, MLP (seed 2)", "burgers_mlp_seed2", "BMLP"),
    ("Burgers, Fourier (seed 2)", "burgers_fourier_seed2", "BFourier"),
    ("Allen--Cahn, MLP (seed 0)", "allen_cahn_mlp_seed0", "ACMLP"),
    ("Allen--Cahn, Fourier (seed 0)", "allen_cahn_fourier_seed0", "ACFourier"),
]


def fmt(x, places=1):
    return f"{x:.{places}f}"


def require_close(where, got, want, rtol=1e-12):
    got, want = float(got), float(want)
    if not (math.isfinite(got) and math.isfinite(want)):
        raise SystemExit(f"{where}: non-finite value ({got}, {want})")
    if abs(got - want) > rtol * max(1.0, abs(got), abs(want)):
        raise SystemExit(f"{where}: summary has {got:.17g}, current artifact has {want:.17g}")


def load_artifact(tag):
    path = ROOT / "results" / tag / f"{tag}_loading_perpoint.json"
    if not path.exists():
        raise SystemExit(f"{path}: missing schema-v3 loading artifact")
    a = json.loads(path.read_text())
    if a.get("schema") != SCHEMA or a.get("tag") != tag:
        raise SystemExit(
            f"{path}: expected schema/tag {SCHEMA!r}/{tag!r}, found "
            f"{a.get('schema')!r}/{a.get('tag')!r}"
        )
    if (a.get("scope"), a.get("eps_mult"), a.get("sigma_metric"), a.get("want_resolved")) \
            != ("full", 1.0, "raw", False):
        raise SystemExit(f"{path}: not the unsuffixed full-scope raw primary artifact")
    if not all(v.get("inside") for v in a.get("sandwich", {}).values()):
        raise SystemExit(f"{path}: stored-sigma sandwich is absent or failed")
    return path, a


def main():
    if not SUMMARY.exists():
        raise SystemExit(
            f"{SUMMARY}: missing; first run analysis/loading_table.py --check successfully"
        )
    data = json.loads(SUMMARY.read_text())
    if data.get("schema") != SCHEMA:
        raise SystemExit(f"{SUMMARY}: expected {SCHEMA!r}, found {data.get('schema')!r}")
    rows = data["canonical"]
    lines = ["% Generated by analysis/loading_table_tex.py; do not edit by hand."]
    perpoint = []
    for label, tag, macro in CANON:
        if label not in rows:
            raise SystemExit(f"{SUMMARY}: missing canonical row {label!r}")
        r = rows[label]
        artifact, a = load_artifact(tag)
        if r.get("tag") != tag:
            raise SystemExit(f"{SUMMARY}: row {label!r} declares tag {r.get('tag')!r}")
        art_perpoint = a["ratio_perpoint_sl"]
        art_mean = a["ratio_mean_tangent_sl"]
        art_quotient = art_mean / art_perpoint
        require_close(f"{label} per-point", r["per_point"], art_perpoint)
        require_close(f"{label} mean-tangent", r["mean_tangent"], art_mean)
        require_close(f"{label} coherence quotient", r["quotient"], art_quotient)
        band = a["sandwich"]
        lo = math.sqrt(band["sharp"]["lower"] / band["bulk"]["upper"])
        hi = math.sqrt(band["sharp"]["upper"] / band["bulk"]["lower"])
        if not (0 < lo <= hi and math.isfinite(lo) and math.isfinite(hi)):
            raise SystemExit(f"{artifact}: invalid regional RMS bracket [{lo}, {hi}]")
        vals = {
            "PerPoint": fmt(r["per_point"]),
            "MeanTangent": fmt(r["mean_tangent"]),
            "CoherenceQuotient": fmt(r["quotient"], 2),
            "RMSBandAtAlpha": f"[{fmt(lo, 2)},\\,{fmt(hi, 1)}]",
        }
        for suffix, value in vals.items():
            lines.append(f"\\newcommand{{\\Loading{macro}{suffix}}}{{{value}}}")
        perpoint.append(r["per_point"])

    spread = data["seed_spread"]
    if spread.get("n") != 8:
        raise SystemExit("seed-spread macros require all eight Burgers-MLP seeds")
    seed_values = {"per_point": [], "mean_tangent": []}
    for seed in range(8):
        tag = f"burgers_mlp_seed{seed}"
        _, a = load_artifact(tag)
        seed_values["per_point"].append(float(a["ratio_perpoint_sl"]))
        seed_values["mean_tangent"].append(float(a["ratio_mean_tangent_sl"]))
    for key, macro in (("per_point", "PerPoint"), ("mean_tangent", "MeanTangent")):
        s = spread[key]
        vals_now = seed_values[key]
        mean_now = sum(vals_now) / len(vals_now)
        sd_now = math.sqrt(sum((x - mean_now) ** 2 for x in vals_now) / len(vals_now))
        checks = {
            "mean": mean_now, "sd": sd_now, "min": min(vals_now), "max": max(vals_now),
            "max_over_min": max(vals_now) / min(vals_now),
        }
        for stat, current in checks.items():
            require_close(f"seed spread {key}.{stat}", s[stat], current)
        if len(s.get("per_seed", [])) != 8:
            raise SystemExit(f"seed spread {key}: missing ordered per-seed values")
        for seed, (summarised, current) in enumerate(zip(s["per_seed"], vals_now)):
            require_close(f"seed spread {key}, seed {seed}", summarised, current)
        lines.extend([
            f"\\newcommand{{\\LoadingSeed{macro}Min}}{{{fmt(s['min'])}}}",
            f"\\newcommand{{\\LoadingSeed{macro}Max}}{{{fmt(s['max'])}}}",
            f"\\newcommand{{\\LoadingSeed{macro}Factor}}{{{fmt(s['max_over_min'], 2)}}}",
        ])
    lines.extend([
        f"\\newcommand{{\\LoadingCanonicalPerPointMin}}{{{fmt(min(perpoint))}}}",
        f"\\newcommand{{\\LoadingCanonicalPerPointMax}}{{{fmt(max(perpoint))}}}",
    ])

    rendered = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists():
            raise SystemExit(f"{OUT}: missing; generate it before the release check")
        if OUT.read_text() != rendered:
            raise SystemExit(f"{OUT}: stale relative to the validated schema-v3 artifacts")
        print(f"CHECK OK -- {OUT} matches all current schema-v3 artifacts")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    tmp = OUT.with_suffix(OUT.suffix + ".partial")
    tmp.write_text(rendered)
    tmp.replace(OUT)
    print(OUT)


if __name__ == "__main__":
    main()
