"""Make the compact centre and root tables from the reviewed all-17 outputs."""
import argparse
import csv
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=ROOT / "outputs/review/paper_tables")
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    with (ROOT / "outputs/review/full_grid_errors.csv").open() as f:
        rows = list(csv.DictReader(f))
    lookup = {(r["tag"], r["setting"], r["centre"]): float(r["full_grid_error_rms"]) for r in rows}
    families = [("burgers_mlp", "Burgers--MLP"), ("burgers_fourier", "Burgers--Fourier"),
                ("allen_cahn_mlp", "Allen--Cahn--MLP"), ("allen_cahn_fourier", "Allen--Cahn--Fourier")]
    lines = [r"% Generated by scripts/make_paper_tables.py from reviewed theta outputs.",
             r"\begin{table}[t]", r"\centering\small\setlength{\tabcolsep}{3pt}",
             r"\begin{tabular}{@{}lrr*{6}{r}@{}}", r"\toprule",
             r" & & & \multicolumn{3}{c}{Baseline} & \multicolumn{3}{c}{Conditional MLE} \\",
             r"\cmidrule(lr){4-6}\cmidrule(l){7-9}",
             r"family & $n$ & trained & zero & $\theta$ & nonlinear & zero & $\theta$ & nonlinear \\",
             r"\midrule"]
    for family, label in families:
        tags = sorted({r["tag"] for r in rows if r["family"] == family})
        trained = [lookup[tag, "baseline", "trained"] for tag in tags]
        cells = [label, f"${len(tags)}$", f"${np.mean(trained):.4g}$"]
        for setting in ("baseline", "conditional_noise_mle"):
            for centre in ("zero_affine", "theta_affine", "theta_nonlinear"):
                values = [lookup[tag, setting, centre] for tag in tags]
                worse = sum(value > reference for value, reference in zip(values, trained))
                cells.append(f"${np.mean(values):.4g}^{{({worse})}}$")
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
        r"\caption{Paired full-grid RMS prediction errors. Entries are unweighted means",
        r"of per-run RMS errors; superscripts count runs worse than the trained predictor",
        r"out of $n$. Baseline uses $(\alpha_0,1)$ and MLE uses $(\alpha_0,\widehat v)$.",
        r"Zero and $\theta$ denote the two affine prior-centre predictions; nonlinear",
        r"is $u_{\theta+\delta_L}$, a forward diagnostic rather than a posterior mean.",
        r"All comparisons retain the original covariance linearisation.}",
        r"\label{tab:r2-centres}", r"\end{table}"]
    (args.out / "round2_centre_table.tex").write_text("\n".join(lines)+"\n", encoding="utf-8")

    with (ROOT / "inputs/refined_roots.csv").open() as f:
        brackets = {r["tag"]: r for r in csv.DictReader(f)}
    with (ROOT / "outputs/review/root_comparisons.csv").open() as f:
        roots = [r for r in csv.DictReader(f) if r["centre"] == "trained"
                 and r["subset"] == "full" and r["calibration"] == "bulk_68_oracle"
                 and r["region"] == "sharp"]
    precision_text = {0: "0.02105515", 4: "0.73626974", 5: r"2.0476385\times10^{-5}",
                      6: "0.00163541", 7: r"3.0590419\times10^{-5}"}
    lines = [r"% Generated by scripts/make_paper_tables.py; old bounds and new direct evaluations.",
             r"\begin{table}[t]", r"\centering\small\setlength{\tabcolsep}{4pt}",
             r"\begin{tabular}{@{}rrrcr c@{}}", r"\toprule",
             r" & & \multicolumn{2}{c}{Sharp $1\sigma$ coverage} & \multicolumn{2}{c}{Sharp $1.96\sigma$ coverage} \\",
             r"\cmidrule(lr){3-4}\cmidrule(l){5-6}",
             r"seed & refined $\gamma$ & direct & envelope & direct & envelope \\", r"\midrule"]
    for r in sorted(roots, key=lambda x: x["tag"]):
        b = brackets[r["tag"]]
        seed = int(r["tag"].rsplit("seed", 1)[1])
        cells = [f"${seed}$", f"${precision_text[seed]}$"]
        for level in ("68", "95"):
            direct = float(r[f"coverage{level}"])
            lower, upper = float(b[f"sharp_coverage{level}_lower"]), float(b[f"sharp_coverage{level}_upper"])
            assert lower <= direct <= upper
            cells += [f"${direct:.5g}$", f"$[{lower:g},{upper:g}]$"]
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}",
        r"\caption{Direct sharp coverage and saved envelopes at five trained Burgers--MLP",
        r"roots. Displayed precisions are rounded; root brackets have relative width below",
        r"$5.3\times10^{-13}$. Bulk calibration uses the higher empirical $0.68$ quantile.",
        r"Envelopes include root and calibration uncertainty through",
        r"\eqref{eq:r3:coverage-envelope}; all direct values lie inside.}",
        r"\label{tab:r3-roots}", r"\end{table}"]
    (args.out / "round3_math_root_table.tex").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print(f"Generated paired centre and root tables in {args.out}")


if __name__ == "__main__":
    main()
